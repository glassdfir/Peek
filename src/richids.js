const MAP = new Map();
for (const line of TABLE.split('\n')) { const [id, name] = line.trim().split(/\s+/); if (name) MAP.set(parseInt(id, 16), name); }

export function richProductName(productId) {
  return MAP.get(productId) || null;
}

// Rough Visual Studio generation from a tool id, for the summary line.
export function richToolchain(productId) {
  const n = richProductName(productId) || '';
  const m = n.match(/(\d{3,4})p?$/) || n.match(/Utc(\d{2,4})/) || n.match(/Phx(\d{4})/);
  if (!m) return null;
  const v = m[1];
  const vs = { '1900': 'VS 2015-2022', '1810': 'VS 2013 Upd', '1800': 'VS 2013', '1700': 'VS 2012', '1610': 'VS 2010 SP1', '1600': 'VS 2010',
    '1500': 'VS 2008', '1400': 'VS 2005', '1310': 'VS .NET 2003', '1300': 'VS .NET 2002', '1200': 'VS 2013', '1210': 'VS 2013 Upd', '1100': 'VS 2012',
    '1010': 'VS 2010 SP1', '1000': 'VS 2010', '900': 'VS 2008', '800': 'VS 2005', '710': 'VS .NET 2003', '700': 'VS .NET 2002', '600': 'VS 6', '12': 'VS 6', '13': 'VS .NET' };
  return vs[v] || null;
}
